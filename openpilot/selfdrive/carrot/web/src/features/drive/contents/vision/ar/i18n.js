function normalizeArLanguage(raw) {
  const code = String(raw || "").toLowerCase();
  if (code.startsWith("zh")) return "zh";
  if (code.startsWith("en")) return "en";
  if (code.startsWith("ko")) return "ko";
  return "";
}

function initialArLanguage() {
  try {
    const code = normalizeArLanguage(globalThis.document?.documentElement?.lang);
    if (code) return code;
  } catch (_) { /* 워커 등 DOM 없는 환경 */ }
  return "ko";
}

let arLanguage = initialArLanguage();

/** 메인 스레드는 <html lang>, 워커는 프레임 payload 로 이 값을 맞춘다. */
export function setArLanguage(raw) {
  const code = normalizeArLanguage(raw);
  if (code) arLanguage = code;
}

export function currentArLanguage() {
  return arLanguage;
}

/** 번역이 없으면 원래 한국어 fallback 을 그대로 돌려준다(안전한 기본값). */
export function arText(key, fallback = "", vars = null) {
  const table = AR_STRINGS[arLanguage] || AR_STRINGS.ko;
  let value = table[key] ?? fallback;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}